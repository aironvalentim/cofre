-- ── Credenciais ───────────────────────────────────────────────
create table if not exists public.credenciais (
  id                  bigint generated by default as identity primary key,
  usuario_id          bigint not null,
  categoria_id        integer not null,
  titulo_enc          text not null,
  login_enc           text null,
  senha_enc           text not null,
  url_ou_banco_enc    text null,
  senha_4dig_enc      text null,
  senha_6dig_enc      text null,
  numero_cartao_enc   text null,
  pin_dispositivo_enc text null,
  conta_vinculada_enc text null,
  notas_enc           text null,
  campos_extras_enc   text null,
  favorito            boolean not null default false,
  criado_em           timestamp(6) not null default current_timestamp(6),
  atualizado_em       timestamp(6) not null default current_timestamp(6),
  excluido_em         timestamp(6) null,
  constraint fk_credenciais_usuario
    foreign key (usuario_id) references public.usuarios (id) on delete cascade,
  constraint fk_credenciais_categoria
    foreign key (categoria_id) references public.categorias_credenciais (id)
);

create index if not exists idx_credenciais_usuario  on public.credenciais (usuario_id);
create index if not exists idx_credenciais_categoria on public.credenciais (categoria_id);

drop trigger if exists trg_credenciais_updated_em on public.credenciais;
create trigger trg_credenciais_updated_em
before update on public.credenciais
for each row execute function public.set_updated_em();

-- ── Cobranças Pix ─────────────────────────────────────────────
