-- ── Função trigger updated_at ─────────────────────────────────
create or replace function public.set_updated_em()
returns trigger language plpgsql as $$
begin
  new.atualizado_em := current_timestamp(6);
  return new;
end;
$$;

create or replace function public.set_preferencias_definido_em()
returns trigger language plpgsql as $$
begin
  new.definido_em := current_timestamp(6);
  return new;
end;
$$;

-- ── Usuários ──────────────────────────────────────────────────
create table if not exists public.usuarios (
  id            bigint generated by default as identity primary key,
  email_hash    text not null,
  email_enc     text not null,
  nome          varchar(100) not null,
  sobrenome     varchar(100) not null,
  senha_hash    varchar(255) not null,
  kdf_salt      text not null,
  verifier_iv   text not null,
  verifier_ct   text not null,
  ativo         boolean not null default true,
  criado_em     timestamp(6) not null default current_timestamp(6),
  atualizado_em timestamp(6) not null default current_timestamp(6)
);

create unique index if not exists uq_usuarios_email_hash on public.usuarios (email_hash);

drop trigger if exists trg_usuarios_atualizado_em on public.usuarios;
create trigger trg_usuarios_atualizado_em
before update on public.usuarios
for each row execute function public.set_updated_em();

