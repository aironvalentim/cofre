-- ── Assinaturas ───────────────────────────────────────────────
create table if not exists public.assinaturas (
  id          bigint generated by default as identity primary key,
  email_hash  text not null,
  plano_id    smallint not null,
  status      text not null default 'ATIVA',
  inicio_em   timestamp(6) not null default current_timestamp(6),
  expira_em   timestamp(6) not null,
  txid_origem varchar(35) null,
  constraint ck_assinaturas_status check (status in ('ATIVA','EXPIRADA','CANCELADA')),
  constraint fk_assinaturas_plano foreign key (plano_id) references public.planos (id)
);

create index if not exists idx_assinaturas_email  on public.assinaturas (email_hash);
create index if not exists idx_assinaturas_expira on public.assinaturas (expira_em);

