-- ── Sessões ───────────────────────────────────────────────────
create table if not exists public.sessoes (
  id         bigint generated by default as identity primary key,
  usuario_id bigint not null,
  token_hash varchar(128) not null,
  ip_origem  varchar(45) null,
  expira_em  timestamp(6) not null,
  criado_em  timestamp(6) not null default current_timestamp(6),
  constraint uq_sessoes_token unique (token_hash),
  constraint fk_sessoes_usuario
    foreign key (usuario_id) references public.usuarios (id) on delete cascade
);

create index if not exists idx_sessoes_usuario on public.sessoes (usuario_id);

-- ── Log de acessos ────────────────────────────────────────────
create table if not exists public.log_acessos (
  id             bigint generated by default as identity primary key,
  email_hash     text null,
  ip_origem      varchar(45) null,
  user_agent     varchar(500) null,
  sucesso        boolean not null default false,
  motivo_falha   varchar(100) null,
  plano_na_epoca varchar(20) null,
  criado_em      timestamp(6) not null default current_timestamp(6)
);

create index if not exists idx_log_acessos_email     on public.log_acessos (email_hash);
create index if not exists idx_log_acessos_criado_em on public.log_acessos (criado_em);

-- ── Histórico de sessões ──────────────────────────────────────
create table if not exists public.historico_sessoes (
  id           bigint generated by default as identity primary key,
  usuario_id   bigint not null,
  email_hash   text not null,
  ip_origem    varchar(45) null,
  user_agent   varchar(500) null,
  plano_ativo  varchar(20) null,
  iniciou_em   timestamp(6) not null default current_timestamp(6),
  encerrou_em  timestamp(6) null,
  motivo_saida varchar(30) null,
  constraint fk_historico_sessoes_usuario
    foreign key (usuario_id) references public.usuarios (id) on delete cascade
);

create index if not exists idx_historico_sessoes_usuario   on public.historico_sessoes (usuario_id);
create index if not exists idx_historico_sessoes_email     on public.historico_sessoes (email_hash);
create index if not exists idx_historico_sessoes_iniciou_em on public.historico_sessoes (iniciou_em);
create index if not exists idx_historico_sessoes_plano     on public.historico_sessoes (plano_ativo);

-- ── Preferências do usuário ───────────────────────────────────
create table if not exists public.preferencias_usuario (
